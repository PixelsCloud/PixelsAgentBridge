#!/usr/bin/env python3
"""Vendor official Lucide SVGs and generate Android vectors without redrawing icons.

Run --download once when deliberately updating the pinned upstream release.
Ordinary generation and --check work offline using the hash-verified sources.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import tomllib
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'apps/android/third-party/lucide'
OUTPUT = ROOT / 'apps/android/platform/src/main/res/drawable'
VERSION = '0.468.0'
ICONS = {
    'HOME': 'house', 'FOLDER': 'folder', 'ACTIVITY': 'list', 'SETTINGS': 'settings',
    'CHEVRON': 'chevron-right', 'COPY': 'copy', 'EYE': 'eye', 'HIDE': 'eye-off',
    'ROTATE': 'rotate-cw', 'PAUSE': 'pause', 'CHECK': 'check', 'SCREEN': 'monitor',
    'BELL': 'bell', 'PHONE': 'smartphone', 'LOCK': 'lock-keyhole', 'PALETTE': 'palette',
    'GLOBE': 'globe', 'LINK': 'link', 'HELP': 'circle-help', 'INFO': 'info',
    'MORE': 'ellipsis-vertical', 'PLUS': 'circle-plus', 'BACK': 'arrow-left',
    'DOCUMENT': 'file-text', 'UPLOAD': 'upload', 'POINTER': 'mouse-pointer-2',
}
BOLD = {'HOME', 'FOLDER', 'ACTIVITY', 'SETTINGS'}


def path_data(node):
    tag = node.tag.split('}')[-1]
    a = node.attrib
    if tag == 'path':
        return a['d']
    if tag == 'circle':
        x, y, r = (float(a[key]) for key in ('cx', 'cy', 'r'))
        return f'M{x-r:g} {y:g}a{r:g} {r:g} 0 1 0 {2*r:g} 0a{r:g} {r:g} 0 1 0 {-2*r:g} 0'
    if tag == 'rect':
        x, y, w, h = (float(a.get(key, 0)) for key in ('x', 'y', 'width', 'height'))
        rx = min(float(a.get('rx', a.get('ry', 0))), w/2)
        ry = min(float(a.get('ry', a.get('rx', 0))), h/2)
        if rx and ry:
            return (f'M{x+rx:g} {y:g}H{x+w-rx:g}a{rx:g} {ry:g} 0 0 1 {rx:g} {ry:g}'
                    f'V{y+h-ry:g}a{rx:g} {ry:g} 0 0 1 {-rx:g} {ry:g}'
                    f'H{x+rx:g}a{rx:g} {ry:g} 0 0 1 {-rx:g} {-ry:g}'
                    f'V{y+ry:g}a{rx:g} {ry:g} 0 0 1 {rx:g} {-ry:g}Z')
        return f'M{x:g} {y:g}h{w:g}v{h:g}h{-w:g}Z'
    if tag == 'line':
        return f'M{a["x1"]} {a["y1"]}L{a["x2"]} {a["y2"]}'
    if tag in ('polyline', 'polygon'):
        return 'M' + a['points'] + ('Z' if tag == 'polygon' else '')
    raise ValueError('Unsupported SVG element: ' + tag)


def vector(data, width):
    svg = ET.fromstring(data)
    assert svg.attrib['viewBox'] == '0 0 24 24'
    paths = [path_data(node) for node in svg]
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by scripts/android_icons.py from official Lucide SVG. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp" android:height="24dp"\n'
            '    android:viewportWidth="24" android:viewportHeight="24">\n'
            + ''.join(f'    <path android:pathData="{path}" android:fillColor="@android:color/transparent"\n'
                      f'        android:strokeColor="#FFFFFFFF" android:strokeWidth="{width}"\n'
                      '        android:strokeLineCap="round" android:strokeLineJoin="round" />\n'
                      for path in paths) + '</vector>\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--download', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.download:
        SOURCE.mkdir(parents=True, exist_ok=True)
        records = []
        for name in (*ICONS.values(), 'LICENSE'):
            upstream = 'LICENSE' if name == 'LICENSE' else f'icons/{name}.svg'
            data = urllib.request.urlopen(
                f'https://raw.githubusercontent.com/lucide-icons/lucide/{VERSION}/{upstream}',
                timeout=30).read()
            relative = 'LICENSE' if name == 'LICENSE' else f'icons/{name}.svg'
            path = SOURCE / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            records.append(f'\n[[source]]\npath = "{relative}"\nsha256 = "{hashlib.sha256(data).hexdigest()}"\n')
        (SOURCE / 'sources.toml').write_text(
            f'version = "{VERSION}"\nupstream = "https://github.com/lucide-icons/lucide"\n'
            + ''.join(records), encoding='utf-8')
    manifest = tomllib.loads((SOURCE / 'sources.toml').read_text(encoding='utf-8'))
    assert manifest['version'] == VERSION
    for record in manifest['source']:
        assert hashlib.sha256((SOURCE / record['path']).read_bytes()).hexdigest() == record['sha256']
    generated = {}
    for glyph, name in ICONS.items():
        data = (SOURCE / f'icons/{name}.svg').read_bytes()
        generated[OUTPUT / f'lucide_{name.replace("-", "_")}.xml'] = vector(data, 2)
        if glyph in BOLD:
            generated[OUTPUT / f'lucide_{name.replace("-", "_")}_bold.xml'] = vector(data, 2.5)
    generated[ROOT / 'apps/android/app/src/main/assets/licenses/lucide.txt'] = (SOURCE / 'LICENSE').read_text(encoding='utf-8')
    for path, text in generated.items():
        if args.check:
            assert path.read_text(encoding='utf-8') == text, f'Stale generated icon: {path}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8', newline='\n')
    print(f'Lucide {VERSION}: {len(ICONS)} official icons, {len(BOLD)} selected weights verified')


if __name__ == '__main__':
    main()
