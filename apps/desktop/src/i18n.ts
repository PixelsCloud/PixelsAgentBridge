export function initialLanguage(): Language {
  const saved = window.localStorage.getItem("pab.language");
  if (saved === "zh-CN" || saved === "en") {
    return saved;
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}
