export function initialLanguage(): Language {
  const saved = window.localStorage.getItem("pab.language");
  if (saved === "zh-CN" || saved === "en") return saved;
  if (saved?.toLowerCase().startsWith("zh")) {
    // Migrate removed Chinese variants without changing other preferences.
    try { window.localStorage.setItem("pab.language", "zh-CN"); } catch { /* Storage may be read-only. */ }
    return "zh-CN";
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}
