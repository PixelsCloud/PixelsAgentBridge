export function initialLanguage(): Language {
  const saved = window.localStorage.getItem("pab.language");
  if (saved === "zh-CN" || saved === "zh-TW" || saved === "en") {
    return saved;
  }
  const system = navigator.language.toLowerCase();
  if (system.startsWith("zh-tw") || system.startsWith("zh-hk")
    || system.startsWith("zh-mo") || system.startsWith("zh-hant")) return "zh-TW";
  return system.startsWith("zh") ? "zh-CN" : "en";
}
