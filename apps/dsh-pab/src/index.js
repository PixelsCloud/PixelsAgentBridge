/**
 * Pixels control panel — host half.
 *
 * Owns a private `pab-mcp` process (the Pixels Agent Bridge MCP server) and
 * re-exposes the few operations the browser panel needs as same-origin HTTP
 * routes. Sign-in, device pairing and status use the pab-mcp CLI (passwords
 * travel on stdin); everything else is a JSON-RPC `tools/call` against the
 * long-lived MCP process.
 *
 * Two environment details are load-bearing:
 *  - PAB_LOG_DIR points at our own directory. pab-mcp opens a fixed-name log
 *    file exclusively, so a second process sharing the default log root dies
 *    with "could not initialize log file: Access is denied".
 *  - The rest of the data root stays shared, so the panel signs into and lists
 *    exactly the same account and devices as an installed Pixels desktop app.
 *
 * No third-party dependencies: `pab-mcp` ships in `native/<platform>-<arch>/`.
 */
import { spawn } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const name = 'dsh-pab'
export const inject = ['webServer']

const here = path.dirname(fileURLToPath(import.meta.url))
const PACKAGE_DIR = path.resolve(here, '..')
const ASSETS_DIR = path.join(PACKAGE_DIR, 'assets')

const STATE_DIR = process.env.PAB_PANEL_STATE_DIR
  || path.join(process.env.LOCALAPPDATA || process.env.XDG_STATE_HOME || os.homedir(), 'dsh-pab')

// Same defaults the shipped client configuration uses. They are spelled out
// here because the plugin may run a build output that has no config.toml.
const DEFAULT_CONTROL_URL = 'wss://pab.rgaa.vip/control'
const DEFAULT_RELAY_URL = 'https://pab-relay.rgaa.vip'

// Panel-owned settings live next to the plugin's state; TOML per repo policy.
const SETTINGS_PATH = path.join(STATE_DIR, 'settings.toml')

function readSettings() {
  const settings = { controlUrl: '', relayUrls: '' }
  try {
    for (const line of readFileSync(SETTINGS_PATH, 'utf8').split(/\r?\n/)) {
      const match = /^\s*([A-Za-z]+)\s*=\s*"([^"]*)"\s*$/.exec(line)
      if (!match) continue
      if (match[1] === 'controlUrl') settings.controlUrl = match[2].trim()
      if (match[1] === 'relayUrls') settings.relayUrls = match[2].trim()
    }
  } catch { /* no settings yet */ }
  return settings
}

function writeSettings(next) {
  mkdirSync(STATE_DIR, { recursive: true })
  const body = [
    '# Pixels Agent Bridge panel settings.',
    '# Empty values fall back to the shipped service.',
    `controlUrl = "${next.controlUrl || ''}"`,
    `relayUrls = "${next.relayUrls || ''}"`,
    '',
  ].join('\n')
  writeFileSync(SETTINGS_PATH, body, 'utf8')
}

function effectiveEndpoints(config) {
  const settings = readSettings()
  return {
    controlUrl: config?.controlUrl || settings.controlUrl || process.env.PAB_CONTROL_URL || DEFAULT_CONTROL_URL,
    relayUrls: config?.relayUrl || settings.relayUrls || process.env.PAB_RELAY_URLS || DEFAULT_RELAY_URL,
  }
}

// The plugin keeps its own data root and its own client config, so an installed
// Pixels Agent Bridge desktop app neither reads nor overrides this panel's
// endpoints, accounts, devices or history.
const DATA_DIR = path.join(STATE_DIR, 'data')
const CONFIG_PATH = path.join(STATE_DIR, 'operator.toml')

function writeOperatorConfig(endpoints) {
  mkdirSync(STATE_DIR, { recursive: true })
  const relays = endpoints.relayUrls.split(',').map((url) => url.trim()).filter(Boolean)
  const body = [
    '# Generated by the Pixels Agent Bridge DeepSeek Harness panel.',
    `control_url = "${endpoints.controlUrl}"`,
    `relay_urls = [${relays.map((url) => `"${url}"`).join(', ')}]`,
    '',
  ].join('\n')
  writeFileSync(CONFIG_PATH, body, 'utf8')
}

/** Arguments every pab-mcp spawn gets: explicit config, private data root. */
function pabArgs() {
  return ['--config', CONFIG_PATH]
}

/** Pull the account's saved-device catalog, throttled to once a minute. */
let catalogSyncedAt = 0
async function ensureCatalogSync(config) {
  if (Date.now() - catalogSyncedAt < 60_000) return
  catalogSyncedAt = Date.now()
  await runCli(['account', 'devices', 'sync'], undefined, config).catch(() => {})
}

/** HTTP reachability probe used to validate a candidate endpoint. */
async function probe(url) {
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), 5000)
  try {
    const response = await fetch(url, { method: 'GET', redirect: 'manual', signal: controller.signal })
    return response.status > 0
  } catch {
    return false
  } finally {
    clearTimeout(timer)
  }
}

/**
 * Resolve the pab-mcp executable. The plugin deliberately does not vendor the
 * binary: inside this repository it runs the cargo build output, and a packaged
 * install is expected to supply `native/<platform>-<arch>/` or point
 * PAB_MCP_PATH at one.
 *
 * Whatever the source, the process runs from our own state directory. A
 * directory that DSH prepared for workspace-write is Low-labelled, and a
 * Low-labelled executable starts at Low integrity and cannot write outside the
 * labelled tree — which breaks pab-mcp's own logging. The copy inherits the
 * destination directory's label instead.
 */
function executable() {
  if (process.env.PAB_MCP_PATH) return process.env.PAB_MCP_PATH
  const exe = process.platform === 'win32' ? 'pab-mcp.exe' : 'pab-mcp'
  const pkgRoot = path.resolve(here, '..')
  const repoRoot = path.resolve(here, '..', '..', '..')
  const candidates = [
    path.join(pkgRoot, 'native', `${process.platform}-${process.arch}`, exe),
    path.join(repoRoot, 'target', 'release', exe),
    path.join(repoRoot, 'target', 'debug', exe),
  ]
  if (process.platform === 'win32') candidates.push('C:\\Program Files\\PixelsAgentBridge\\pab-mcp.exe')

  const source = candidates.find((candidate) => existsSync(candidate))
  if (!source) return exe // fall back to PATH

  try {
    const target = path.join(STATE_DIR, 'bin', exe)
    if (path.resolve(source) === path.resolve(target)) return target
    mkdirSync(path.dirname(target), { recursive: true })
    const stale = !existsSync(target)
      || statSync(source).size !== statSync(target).size
      || statSync(source).mtimeMs !== statSync(target).mtimeMs
    if (stale) copyFileSync(source, target)
    return target
  } catch {
    return source
  }
}

function resolveLogDir() {
  const dir = process.env.PAB_PANEL_LOG_DIR || path.join(STATE_DIR, 'logs')
  mkdirSync(dir, { recursive: true })
  return dir
}

const PAB = executable()
const LOG_DIR = resolveLogDir()

// pab-mcp opens a fixed-name log file exclusively, so two live processes in one
// log directory make the second fail with "could not initialize log file:
// Access is denied". Every spawn gets its own directory, which keeps the
// long-lived MCP process and the short-lived CLI calls from colliding.
let spawnSeq = 0
function baseEnv(config) {
  const dir = path.join(LOG_DIR, `${process.pid}-${++spawnSeq}`)
  mkdirSync(dir, { recursive: true })
  const env = { ...process.env, PAB_LOG_DIR: dir }

  // A pab-mcp started from a build output has no config.toml beside it, so it
  // receives no endpoint environment from its own installer. Supply the
  // effective endpoints explicitly (profile config > panel settings > ambient
  // env > shipped service); an installed binary's config.toml still wins,
  // because pab-mcp applies its own configuration after the inherited one.
  const endpoints = effectiveEndpoints(config)
  env.PAB_CONTROL_URL = endpoints.controlUrl
  env.PAB_RELAY_URLS = endpoints.relayUrls
  // Private data root: accounts, device passwords, history and terminal archives
  // stay inside the plugin's own directory instead of the desktop app's.
  mkdirSync(DATA_DIR, { recursive: true })
  env.PAB_DATA_DIR = DATA_DIR
  return env
}

/** One long-lived `pab-mcp` speaking line-delimited JSON-RPC over stdio. */
class McpBridge {
  constructor(config) {
    this.config = config
    this.child = null
    this.seq = 0
    this.pending = new Map()
    this.buffer = ''
    this.ready = null
    this.stderr = ''
    this.state = 'idle'
    this.error = null
  }

  start() {
    if (this.ready) return this.ready
    this.state = 'starting'
    this.error = null
    this.child = spawn(PAB, pabArgs(), {
      stdio: ['pipe', 'pipe', 'pipe'],
      windowsHide: true,
      env: baseEnv(this.config),
    })
    this.child.stdout.setEncoding('utf8')
    this.child.stderr.setEncoding('utf8')
    this.child.stdout.on('data', (chunk) => this.#feed(chunk))
    this.child.stderr.on('data', (chunk) => { this.stderr = (this.stderr + chunk).slice(-8192) })
    this.child.on('error', (err) => { this.error = err.message; this.state = 'failed' })
    this.child.on('exit', (code) => {
      this.child = null
      this.ready = null
      if (this.state !== 'failed') this.state = code === 0 ? 'stopped' : 'failed'
    })
    this.ready = this.#handshake().then(
      () => { this.state = 'ready' },
      (err) => { this.error = err.message; this.state = 'failed'; this.ready = null; throw err },
    )
    return this.ready
  }

  #feed(chunk) {
    this.buffer += chunk
    let index
    while ((index = this.buffer.indexOf('\n')) >= 0) {
      const line = this.buffer.slice(0, index).trim()
      this.buffer = this.buffer.slice(index + 1)
      if (!line) continue
      let message
      try { message = JSON.parse(line) } catch { continue }
      if (message.id === undefined || message.id === null) continue
      const waiter = this.pending.get(message.id)
      if (!waiter) continue
      this.pending.delete(message.id)
      if (message.error) waiter.reject(new Error(message.error.message ?? JSON.stringify(message.error)))
      else waiter.resolve(message.result)
    }
  }

  #write(payload) {
    if (!this.child) throw new Error('pab-mcp is not running')
    this.child.stdin.write(JSON.stringify(payload) + '\n')
  }

  #request(method, params, timeoutMs = 60_000) {
    const id = ++this.seq
    return new Promise((resolve, reject) => {
      const timer = setTimeout(() => {
        this.pending.delete(id)
        reject(new Error(`pab-mcp ${method} timed out after ${timeoutMs} ms`))
      }, timeoutMs)
      this.pending.set(id, {
        resolve: (value) => { clearTimeout(timer); resolve(value) },
        reject: (err) => { clearTimeout(timer); reject(err) },
      })
      try { this.#write({ jsonrpc: '2.0', id, method, params }) } catch (err) {
        clearTimeout(timer)
        this.pending.delete(id)
        reject(err)
      }
    })
  }

  async #handshake() {
    await this.#request('initialize', {
      protocolVersion: '2024-11-05',
      capabilities: {},
      clientInfo: { name: 'dsh-pab', version: '0.1.0' },
    })
    this.#write({ jsonrpc: '2.0', method: 'notifications/initialized' })
  }

  async listTools() {
    await this.start()
    return this.#request('tools/list', {})
  }

  async invoke(tool, args, timeoutMs = 180_000) {
    await this.start()
    return this.#request('tools/call', { name: tool, arguments: args ?? {} }, timeoutMs)
  }

  async restart() {
    await this.stop()
    await this.start()
  }

  async stop() {
    const child = this.child
    this.child = null
    this.ready = null
    this.state = 'stopped'
    for (const waiter of this.pending.values()) waiter.reject(new Error('pab-mcp stopped'))
    this.pending.clear()
    if (!child) return
    await new Promise((resolve) => {
      child.once('exit', resolve)
      child.kill()
      setTimeout(resolve, 3000)
    })
  }
}

/** Run one short-lived `pab-mcp` CLI command; `stdin` never appears in argv. */
function runCli(args, stdin, config) {
  return new Promise((resolve, reject) => {
    const child = spawn(PAB, [...pabArgs(), ...args], {
      stdio: ['pipe', 'pipe', 'pipe'],
      windowsHide: true,
      env: baseEnv(config),
    })
    let out = ''
    let err = ''
    child.stdout.setEncoding('utf8')
    child.stderr.setEncoding('utf8')
    child.stdout.on('data', (d) => { out += d })
    child.stderr.on('data', (d) => { err += d })
    child.on('error', reject)
    child.on('close', (code) => resolve({ code, out: out.trim(), err: err.trim() }))
    child.stdin.end(stdin ?? '')
  })
}

/** Extract the text blocks of one MCP `tools/call` result. */
function toolText(result) {
  const content = result && result.content
  if (!Array.isArray(content)) return ''
  return content.filter((c) => c && c.type === 'text').map((c) => c.text).join('\n')
}

function json(res, status, body) {
  res.writeHead(status, { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' })
  res.end(JSON.stringify(body))
}

async function readJson(req) {
  const chunks = []
  for await (const chunk of req) chunks.push(chunk)
  const text = Buffer.concat(chunks).toString('utf8')
  return text ? JSON.parse(text) : {}
}

export function apply(ctx, config) {
  // Materialize the plugin's own client config before the first spawn; the
  // explicit --config keeps an installed desktop app's operator-server.toml out
  // of this process entirely.
  try {
    writeOperatorConfig(effectiveEndpoints(config))
  } catch (err) {
    console.error('[dsh-pab] could not write operator.toml:', err.message)
  }
  const bridge = new McpBridge(config)
  bridge.start().catch((err) => console.error('[dsh-pab] pab-mcp start failed:', err.message))

  // Client-side diagnostics land here so a broken browser half can be inspected
  // from outside the page (the Web GUI offers no DOM/console access to the agent).
  const clientLog = []
  const recordClientLog = (entry) => {
    clientLog.push({ at: new Date().toISOString(), ...entry })
    if (clientLog.length > 50) clientLog.shift()
    console.warn('[dsh-pab] client:', entry.message)
  }

  ctx.effect(() => () => { void bridge.stop() })

  // Raw webServer routes carry no authentication of their own. This shell's
  // index rendering does not run index taps in every composition, so a token
  // injected into the HTML is not reliable. Instead require the two things a
  // cross-site page cannot produce: a same-origin Origin header when one is
  // present, and a custom request header (which forces a CORS preflight this
  // server never approves).
  const authorized = (req) => {
    const origin = req.headers.origin
    if (origin) {
      try {
        if (new URL(origin).host !== req.headers.host) return false
      } catch {
        return false
      }
    }
    return req.headers['x-pixels-client'] === '1'
  }

  ctx.effect(() => ctx.webServer.register({
    kind: 'prefix',
    path: '/x-pixels',
    async handler(req, res) {
      const url = new URL(req.url ?? '/', 'http://localhost')
      const route = url.pathname.slice('/x-pixels'.length) || '/'

      if (route === '/health') {
        return json(res, 200, {
          ok: true,
          state: bridge.state,
          error: bridge.error,
          pab: PAB,
          logDir: LOG_DIR,
        })
      }

      // Read-only diagnostics stay reachable without the page token so a broken
      // browser half can still be inspected from a local shell.
      if (route === '/client-log' && req.method === 'GET') {
        return json(res, 200, { ok: true, entries: clientLog })
      }
      // Static terminal assets (xterm.js + its stylesheet). A <script>/<link>
      // tag cannot carry the custom request header, so these are served without
      // it; they are inert vendor files, not data.
      if (route.startsWith('/assets/') && req.method === 'GET') {
        const name = route.slice('/assets/'.length)
        if (!/^[A-Za-z0-9._-]+$/.test(name)) return json(res, 400, { ok: false, error: 'invalid asset name' })
        try {
          const body = readFileSync(path.join(ASSETS_DIR, name))
          const type = name.endsWith('.css')
            ? 'text/css; charset=utf-8'
            : (name.endsWith('.js') ? 'text/javascript; charset=utf-8' : 'application/octet-stream')
          res.writeHead(200, { 'content-type': type, 'cache-control': 'no-cache' })
          return res.end(body)
        } catch {
          return json(res, 404, { ok: false, error: `no asset ${name}` })
        }
      }

      // The panel UI module. It is fetched by the thin client bundle at apply
      // time, so editing src/ui.js and reloading the page is enough — no
      // DeepSeek Harness restart.
      if (route === '/ui.js' && req.method === 'GET') {
        try {
          const body = readFileSync(path.join(PACKAGE_DIR, 'src', 'ui.js'))
          res.writeHead(200, { 'content-type': 'text/javascript; charset=utf-8', 'cache-control': 'no-store' })
          return res.end(body)
        } catch {
          return json(res, 404, { ok: false, error: 'ui.js not found' })
        }
      }

      if (!authorized(req)) return json(res, 403, { ok: false, error: 'missing or invalid token' })

      try {
        if (route === '/selfcheck') {
          let tools = null
          try {
            const list = await bridge.listTools()
            tools = Array.isArray(list?.tools) ? list.tools.length : null
          } catch { /* reported through state/error */ }
          return json(res, 200, {
            ok: bridge.state === 'ready',
            state: bridge.state,
            tools,
            error: bridge.error,
            stderr: bridge.stderr.slice(-2000),
            pab: PAB,
            logDir: LOG_DIR,
          })
        }

        if (route === '/status' && req.method === 'GET') {
          const status = await runCli(['account', 'status'], undefined, config)
          let account = null
          try { account = JSON.parse(status.out) } catch { /* signed out */ }
          return json(res, 200, {
            ok: true,
            signedIn: Boolean(account?.user),
            user: account?.user ?? null,
            server: effectiveEndpoints(config).controlUrl,
            detail: status.code === 0 ? undefined : status.err,
          })
        }

        if (route === '/settings' && req.method === 'GET') {
          const stored = readSettings()
          const effective = effectiveEndpoints(config)
          return json(res, 200, {
            ok: true,
            controlUrl: stored.controlUrl,
            relayUrls: stored.relayUrls,
            effective,
            defaults: { controlUrl: DEFAULT_CONTROL_URL, relayUrls: DEFAULT_RELAY_URL },
            dataDir: DATA_DIR,
            configPath: CONFIG_PATH,
          })
        }

        if (route === '/settings' && req.method === 'POST') {
          const body = await readJson(req)
          const controlUrl = String(body.controlUrl ?? '').trim()
          const relayUrls = String(body.relayUrls ?? '').trim()
          if (controlUrl && !/^wss:\/\/[^\s]+$/.test(controlUrl)) {
            return json(res, 400, { ok: false, error: '控制服务器必须是 wss:// 地址' })
          }
          if (relayUrls && !relayUrls.split(',').every((url) => /^https:\/\/[^\s]+$/.test(url.trim()))) {
            return json(res, 400, { ok: false, error: '所有 Relay 地址必须是 https:// 地址' })
          }

          // Verify reachability before persisting, the way the desktop app does.
          if (controlUrl) {
            const origin = new URL(controlUrl).host
            if (!(await probe(`https://${origin}/api/account/config`))) {
              return json(res, 200, { ok: false, error: `控制服务器无法访问：${origin}` })
            }
          }
          for (const relay of relayUrls ? relayUrls.split(',').map((url) => url.trim()).filter(Boolean) : []) {
            if (!(await probe(relay))) {
              return json(res, 200, { ok: false, error: `Relay 无法访问：${relay}` })
            }
          }

          const before = effectiveEndpoints(config)
          const after = {
            controlUrl: controlUrl || DEFAULT_CONTROL_URL,
            relayUrls: relayUrls || DEFAULT_RELAY_URL,
          }
          const changed = before.controlUrl !== after.controlUrl || before.relayUrls !== after.relayUrls
          if (changed) {
            // Switching services invalidates the machine-level session: sign out
            // of the previous one first, then restart against the new endpoint.
            await runCli(['account', 'logout'], undefined, config).catch(() => {})
          }
          writeSettings({ controlUrl, relayUrls })
          try { writeOperatorConfig(effectiveEndpoints(config)) } catch { /* surfaced by the restart below */ }
          await bridge.restart().catch(() => {})
          return json(res, 200, {
            ok: true,
            changed,
            signedOut: changed,
            effective: effectiveEndpoints(config),
          })
        }

        if (route === '/login' && req.method === 'POST') {
          const body = await readJson(req)
          const username = String(body.username ?? '').trim()
          const password = String(body.password ?? '')
          if (!username || !password) return json(res, 400, { ok: false, error: 'username and password are required' })
          const args = ['account', body.register ? 'register' : 'login', username, '--password-stdin']
          const result = await runCli(args, password, config)
          if (result.code !== 0) return json(res, 200, { ok: false, error: result.err || 'sign-in failed' })
          // Pull the account's saved-device catalog so the panel can list
          // devices this computer has not paired yet.
          await runCli(['account', 'devices', 'sync'], undefined, config).catch(() => {})
          await bridge.restart().catch(() => {})
          return json(res, 200, { ok: true, detail: result.out })
        }

        if (route === '/logout' && req.method === 'POST') {
          const result = await runCli(['account', 'logout'], undefined, config)
          await bridge.restart().catch(() => {})
          return json(res, 200, { ok: result.code === 0, detail: result.err || result.out })
        }

        if (route === '/device' && req.method === 'POST') {
          const body = await readJson(req)
          const code = String(body.code ?? '').trim()
          const password = String(body.password ?? '')
          if (!/^\d{9}$/.test(code)) return json(res, 400, { ok: false, error: '设备码必须是 9 位数字' })
          if (!password) return json(res, 400, { ok: false, error: 'password is required' })
          const result = await runCli(['device', 'connect', code, '--password-stdin'], password, config)
          if (result.code !== 0) return json(res, 200, { ok: false, error: result.err || 'device pairing failed' })
          await bridge.restart().catch(() => {})
          return json(res, 200, { ok: true, detail: result.out })
        }

        if (route === '/devices' && req.method === 'GET') {
          try {
            const result = await bridge.invoke('pab_list_devices', {})
            return json(res, 200, { ok: true, result })
          } catch (err) {
            return json(res, 200, { ok: false, error: err.message })
          }
        }

        // The panel's device list: the offline-capable local catalog merged with
        // the server's live presence for each remembered device. A device whose
        // presence cannot be read keeps online: null rather than a guessed value.
        if (route === '/presence' && req.method === 'GET') {
          try {
            // Refresh the account's saved-device catalog at most once a minute;
            // it is what makes devices saved on the server visible here.
            await ensureCatalogSync(config)
            // Prefer the account's server catalog: it lists devices this
            // computer has not paired yet (paired=false) and carries presence.
            try {
              const saved = await bridge.invoke('pab_list_saved_devices', {})
              const catalog = JSON.parse(toolText(saved)).devices ?? []
              if (catalog.length > 0) {
                const mapped = catalog.map((device) => ({
                  device_code: device.device_code,
                  name: device.alias || device.name,
                  os: device.os,
                  online: device.online ?? null,
                  paired: Boolean(device.paired),
                }))
                // The catalog's online flag can be stale/absent; ask presence for
                // the entries it did not answer for.
                const enriched = await Promise.all(mapped.map(async (device) => {
                  if (device.online !== null) return device
                  try {
                    const result = await bridge.invoke('pab_device_presence', { device_code: device.device_code }, 30_000)
                    return { ...device, online: Boolean(JSON.parse(toolText(result)).online) }
                  } catch {
                    return device
                  }
                }))
                return json(res, 200, { ok: true, source: 'catalog', devices: enriched })
              }
            } catch { /* older binary or not signed in: fall through */ }

            const listing = await bridge.invoke('pab_list_devices', {})
            const text = toolText(listing)
            const devices = JSON.parse(text).devices ?? []
            const merged = await Promise.all(devices.map(async (device) => {
              try {
                const result = await bridge.invoke('pab_device_presence', { device_code: device.device_code }, 30_000)
                const presence = JSON.parse(toolText(result))
                return { ...device, online: Boolean(presence.online), paired: true }
              } catch {
                return { ...device, online: null, paired: true }
              }
            }))
            return json(res, 200, { ok: true, source: 'local', devices: merged })
          } catch (err) {
            return json(res, 200, { ok: false, error: err.message })
          }
        }

        if (route === '/call' && req.method === 'POST') {
          const body = await readJson(req)
          const tool = String(body.tool ?? '')
          if (!tool.startsWith('pab_')) return json(res, 400, { ok: false, error: 'only pab_* tools are callable' })
          try {
            const result = await bridge.invoke(tool, body.args ?? {})
            return json(res, 200, { ok: true, result })
          } catch (err) {
            return json(res, 200, { ok: false, error: err.message })
          }
        }

        if (route === '/client-log') {
          if (req.method === 'POST') {
            const body = await readJson(req)
            recordClientLog({ message: String(body.message ?? ''), stack: body.stack ?? null })
            return json(res, 200, { ok: true })
          }
          return json(res, 200, { ok: true, entries: clientLog })
        }

        return json(res, 404, { ok: false, error: `no route ${route}` })
      } catch (err) {
        return json(res, 500, { ok: false, error: String(err?.message ?? err) })
      }
    },
  }))
}
